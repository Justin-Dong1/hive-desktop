'use strict';
const assert=require('assert'),fs=require('fs'),os=require('os'),path=require('path');
const create=require('./clock-store');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'hive-clock-test-')),file=path.join(dir,'clock.json');let now=100000;
let store=create(file,()=>now);
store.change({action:'add',kind:'alarm',text:'喝水休息',due:now+5000});
store.change({action:'add',kind:'timer',text:'会议',seconds:10});
const timer=store.read().items[0].id;now+=3000;store.change({action:'pause',id:timer});assert.equal(store.read().items[0].remaining,7000);
now+=10000;assert.equal(store.tick().length,1);assert.equal(store.tick().length,0);
const alarm=store.read().items[1];assert.equal(alarm.status,'fired');assert.equal(alarm.text,'喝水休息');
store.change({action:'ack',id:alarm.id});store.change({action:'resume',id:timer});assert.equal(store.read().items[0].due,now+7000);
store.change({action:'watch:start'});now+=2345;store.change({action:'watch:pause'});assert.equal(store.read().watch.elapsed,2345);
store.change({action:'watch:start'});now+=1000;store=create(file,()=>now);assert.equal(store.read().watch.started,now-1000);
store.change({action:'watch:pause'});assert.equal(store.read().watch.elapsed,3345);
now+=10000;assert.equal(store.tick().length,1);store.change({action:'watch:reset'});assert.equal(store.read().watch.elapsed,0);
assert.throws(()=>store.change({action:'add',kind:'timer',seconds:0,text:''}));
assert.throws(()=>store.change({action:'add',kind:'alarm',due:now-1,text:''}));
assert.throws(()=>store.change({action:'add',kind:'timer',seconds:1,text:'x'.repeat(201)}));
store.change({action:'delete',id:timer});assert.equal(store.read().items.length,1);
const snap=store.read();snap.items.length=0;assert.equal(store.read().items.length,1);
fs.writeFileSync(file,'broken');store=create(file,()=>now);assert.throws(()=>store.read());assert.throws(()=>store.change({action:'watch:reset'}));assert.equal(fs.readFileSync(file,'utf8'),'broken');
console.log('PASS clock: Chinese reminders, pause/resume, one-shot delivery, missed reminders, restart, stopwatch, validation, corrupt-file preservation');
